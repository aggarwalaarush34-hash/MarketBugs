"""Render results/heldout.json into results/RESULTS.md."""

from __future__ import annotations

ORDER = [
    "no_notes", "single.trace", "single.graph", "single.spec", "single.static", "single.semantic",
    "all_notes", "all_notes.T", "linpool", "logpool", "logpool.T", "hedge", "hedge.T",
    "market", "market.cold_start", "market.fresh_per_bug",
]
LABEL = {
    "no_notes": "No notes", "all_notes": "All five notes (one call)",
    "all_notes.T": "All notes + dev temperature", "linpool": "Linear pool (equal)",
    "logpool": "Log pool (equal)", "logpool.T": "Log pool + dev temperature",
    "hedge": "Hedge log pool (dev weights)", "hedge.T": "Hedge + dev temperature",
    "market": "**Market** (frozen, capital from dev)", "market.cold_start": "Market, capital from equal start",
    "market.fresh_per_bug": "Market, fresh capital each bug",
}


def pct(x):
    return "–" if x is None else f"{100 * x:.1f}"


def num(x, d=3):
    return "–" if x is None else f"{x:.{d}f}"


def ci(c, scale=100, d=1):
    return f"{c['mean'] * scale:+.{d}f} [{c['lo'] * scale:+.{d}f}, {c['hi'] * scale:+.{d}f}]"


def render(res: dict) -> str:
    main = res["main"]
    s = main["summary"]
    L = []
    L.append("# Held-out results\n")
    L.append(f"Generated by `python -m marketdebug heldout` from the frozen config in `configs/frozen.json` "
             f"(frozen {res['frozen']['frozen_at_utc']}, code `{res['frozen']['code_sha256'][:12]}`).\n")
    p = main["primary"]
    L.append("## Primary comparison\n")
    L.append(f"Top-1, market minus all-notes, {p['n']} bugs: **{ci(p['cluster'])} pp** "
             f"(two-stage repository-cluster bootstrap, {p['cluster']['reps']} replicates, "
             f"{p['cluster']['clusters']} repositories). Instance-level: {ci(p['instance'])} pp. "
             f"Paired wins / losses / ties: {p['wins']} / {p['losses']} / {p['ties']}. "
             f"Same top-1 pick on {main['market_same_top1_as_all_notes']} of {main['n']} bugs.\n")
    L.append("## All methods (held-out, 210 bugs; NLL and Brier on the "
             f"{s['market']['n_gold_in_pool']} gold-in-pool bugs)\n")
    L.append("| Method | Top-1 | Top-3 | Top-5 | MRR | NLL | Brier | ECE |")
    L.append("|---|---|---|---|---|---|---|---|")
    for m in ORDER:
        if m in s:
            r = s[m]
            L.append(f"| {LABEL.get(m, m)} | {pct(r['top1'])} | {pct(r['top3'])} | {pct(r['top5'])} | "
                     f"{num(r['mrr'])} | {num(r['nll'])} | {num(r['brier'])} | {num(r['ece'])} |")
    L.append("\n## Secondary comparisons (exploratory)\n")
    L.append("| Comparison | ΔTop-1 pp, cluster CI | ΔNLL nats, cluster CI | ΔNLL instance CI |")
    L.append("|---|---|---|---|")
    for k, v in main["comparisons"].items():
        L.append(f"| {k} | {ci(v['top1']['cluster'])} | {ci(v['nll']['cluster'], 1, 3)} | {ci(v['nll']['instance'], 1, 3)} |")
    L.append("\n## Per repository (top-1 % / NLL)\n")
    ms = ["market", "all_notes", "all_notes.T", "hedge.T"]
    L.append("| Repository | " + " | ".join(LABEL.get(m, m) for m in ms) + " |")
    L.append("|---|" + "---|" * len(ms))
    for repo, d in main["per_repo"].items():
        L.append(f"| {repo} | " + " | ".join(f"{pct(d[m]['top1'])} / {num(d[m]['nll'], 2)}" for m in ms) + " |")
    L.append("\n## Ledgers after the held-out run (credits)\n")
    L.append("| Agent | Capital | Trading P&L | Information | Floor top-ups |")
    L.append("|---|---|---|---|---|")
    for a, x in main["ledgers_after_test"].items():
        L.append(f"| {a} | {x['capital']:.0f} | {x['trading']:+.0f} | {x['information']:+.1f} | {x['floor_topups']:.0f} |")
    L.append(f"\nMarket-maker loss over the held-out markets: {main['maker_loss_total']:+.1f} credits "
             f"({main['voided_markets']} markets voided for retrieval misses). Books balanced: "
             f"{main['audit']['balanced']}.\n")
    cp = res["credit_properties"]
    L.append("## Information credit on dev (exact Shapley, all 32 coalitions, "
             f"{cp['n_bugs']} bugs; log score, nats per bug)\n")
    L.append("| Specialist | Shapley | Pivotal | Marginal range over 120 orders |")
    L.append("|---|---|---|---|")
    for a in cp["mean_shapley"]:
        L.append(f"| {a} | {num(cp['mean_shapley'][a])} | {num(cp['mean_pivotal'][a])} | {num(cp['mean_marginal_range'][a])} |")
    L.append(f"\nShapley budget error (max over bugs): {cp['max_shapley_budget_error']:.2e}. "
             f"Pivotal payouts minus total value: mean {cp['mean_pivotal_budget_gap']:+.3f} nats; "
             f"pivotal overpays on {100 * cp['share_pivotal_overpays']:.0f}% of bugs. "
             f"Top-credited agent changes with reveal order in {100 * cp['mean_rank_flip_fraction']:.0f}% of orders "
             f"under marginal credit. Additive Shapley approximation (used on held-out): "
             f"mean |error| {cp['approx_mean_abs_error']:.3f} nats, same top agent on "
             f"{100 * cp['approx_top_agent_agreement']:.0f}% of bugs.\n")
    cc = res["copycat"]
    L.append("## Copycat test (dev)\n")
    L.append(f"Without the board's dedupe rule, a copycat of `{cc['target']}` takes "
             f"{num(cc['no_dedupe_mean_copycat'])} nats/bug of Shapley credit and leaves the original "
             f"{num(cc['no_dedupe_mean_original'])} (vs {num(cc['original_without_copycat'])} alone). "
             f"With the rule, the copycat's information credit is zero on every bug: "
             f"{cc['copycat_denied_every_time']}.\n")
    L.append("## Ledger ablation (held-out)\n")
    L.append("| Capital moves with | Top-1 | NLL | ΔNLL vs trading only, cluster CI |")
    L.append("|---|---|---|---|")
    for k, v in res["ledger_ablation"].items():
        if k == "dev_only":
            continue
        if "skipped" in v:
            L.append(f"| {k} | skipped | | {v['skipped'][:80]} |")
        else:
            L.append(f"| {k} | {pct(v['summary']['top1'])} | {num(v['summary']['nll'])} | "
                     f"{ci(v['vs_trading_only_nll']['cluster'], 1, 3)} |")
    L.append("\nOn dev (all coalitions cached; 30 bugs):\n")
    L.append("| Capital moves with | Top-1 | NLL |")
    L.append("|---|---|---|")
    for k, v in res["ledger_ablation"]["dev_only"].items():
        L.append(f"| {k} | {pct(v['summary']['top1'])} | {num(v['summary']['nll'])} |")
    L.append("\n## Reveal policy (held-out, information flows into capital)\n")
    L.append("| Policy | Top-1 | NLL |")
    L.append("|---|---|---|")
    for k, v in res["hoarding"].items():
        L.append(f"| {k} | {pct(v['summary']['top1'])} | {num(v['summary']['nll'])} |")
    rb = res["robustness"]
    L.append("\n## Robustness (held-out, exploratory)\n")
    for k in ("turn_order_seeds", "bug_order_seeds"):
        t, n = rb[k]["top1"], rb[k]["nll"]
        L.append(f"- {k.replace('_', ' ')} (20 seeds): top-1 {pct(t['mean'])} (range {pct(t['min'])}–{pct(t['max'])}), "
                 f"NLL {num(n['mean'])} (range {num(n['min'])}–{num(n['max'])})")
    L.append("\n| Parameter | Value | Top-1 | NLL |")
    L.append("|---|---|---|---|")
    for k, d in rb["one_at_a_time"].items():
        for v, r in d.items():
            L.append(f"| {k} | {v} | {pct(r['top1'])} | {num(r['nll'])} |")
    if "repair_sim" in res:
        rs = res["repair_sim"]
        L.append(f"\n## Repair ledger (SYNTHETIC simulation, {rs['n_worlds']} worlds)\n")
        L.append("| Test order | Solve rate | Solve rate when solvable | Tests when solved | Repair share to true-signal agents |")
        L.append("|---|---|---|---|---|")
        for o in ("price", "proposal", "random"):
            r = rs[o]
            L.append(f"| {o} | {pct(r['solve_rate'])} | {pct(r['solve_rate_when_solvable'])} | "
                     f"{num(r['mean_tests_when_solved'], 2)} | {pct(r['repair_share_to_true_signal_agents'])} |")
    return "\n".join(L) + "\n"
